#!/usr/bin/env python3
"""Generates launcher/assets/assets.c: the UI font and the loading screen's D-Tector sprites (24x24 / 16x16 pixel art,
3x upscaled webp downloads, reduced to their native grid: 0 clear, 1 outline, 2 body; mirrored to run to the right).

  gen_assets.py SPRITE_DIR FONT.ttf OUT.c       SPRITE_DIR holds a1-a4 g1-g4 k1-k3 .webp (needs ffmpeg)"""
import subprocess
import sys
from collections import deque

SPRITES = {"a": 4, "g": 4, "k": 3}


def decode(path):
    probe = subprocess.check_output(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                                     "stream=width,height", "-of", "csv=p=0:s=x", path]).decode().strip()
    w, h = map(int, probe.split("x"))
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", path, "-vf", "hflip", "-f", "rawvideo",
                                   "-pix_fmt", "rgba", "-"])
    return w, h, raw


def native(path):
    w, h, raw = decode(path)
    cell = 3
    nw, nh = w // cell, h // cell

    def black(x, y):
        i = ((y * cell + 1) * w + x * cell + 1) * 4
        r, g, b, a = raw[i:i + 4]
        return a > 128 and (r * 30 + g * 59 + b * 11) // 100 < 140

    bl = [[black(x, y) for x in range(nw)] for y in range(nh)]
    bg = [[False] * nw for _ in range(nh)]
    q = deque()
    for x in range(nw):
        for y in (0, nh - 1):
            if not bl[y][x] and not bg[y][x]:
                bg[y][x] = True
                q.append((x, y))
    for y in range(nh):
        for x in (0, nw - 1):
            if not bl[y][x] and not bg[y][x]:
                bg[y][x] = True
                q.append((x, y))
    while q:
        cx, cy = q.popleft()
        for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
            if 0 <= nx < nw and 0 <= ny < nh and not bg[ny][nx] and not bl[ny][nx]:
                bg[ny][nx] = True
                q.append((nx, ny))
    return nw, nh, [[0 if bg[y][x] else (1 if bl[y][x] else 2) for x in range(nw)] for y in range(nh)]


def main():
    src, font, out = sys.argv[1:4]
    lines = ['/* Generated by launcher/tools/gen_assets.py: do not edit. */', '#include "assets.h"', '']
    names = []
    for prefix, count in SPRITES.items():
        for n in range(1, count + 1):
            nw, nh, g = native("%s/%s%d.webp" % (src, prefix, n))
            name = "spr_%s%d" % (prefix, n)
            names.append((name, nw, nh))
            flat = ",".join(str(v) for row in g for v in row)
            lines.append("static const unsigned char %s_px[] = {%s};" % (name, flat))
    lines.append("const Sprite sprites[] = {")
    for name, nw, nh in names:
        lines.append('    { "%s", %d, %d, %s_px },' % (name[4:], nw, nh, name))
    lines.append("};")
    lines.append("const int sprite_count = %d;" % len(names))
    data = open(font, "rb").read()
    lines.append("const unsigned int font_size = %d;" % len(data))
    lines.append("const unsigned char font_data[] = {")
    for i in range(0, len(data), 32):
        lines.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


main()
