#!/usr/bin/env python3
"""The Time Room's trials (owner, 2026-11-17; .plan/tasks/velvet-historia.md): the gatekeeper before the Warp Gate to
the Gunslinger. Each trial is one battle of three enemy members brought in one after the other (a boss battle's native
entrance, as the DRI Gauntlet's), the challenger's own team; the levels climb towards Galacticmon's (65, then 70) so the
three together tell whether the party is ready for the point of no return.

  tools/venv/bin/python tools/gen_time_room.py           # print the table
  tools/venv/bin/python tools/gen_time_room.py --apply   # write port/game/definitive_time_room_table.c

The stats of a species at a level come from its own rows in the game's battles (gen_dri_challenges.stage_of), the
battle it is set up as is an existing boss battle near the trial's top level (no escape, not one of the special ones),
so its kind and immunities are a boss's. The trials give nothing (definitive_time_room.c skips the results screen)."""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import gen_dri_challenges as g  # noqa: E402

GEN = ROOT / "port/game/definitive_time_room_table.c"

# (challenger, the three species in the order they come in, their levels). The third trial is the old man's: the real
# Gennai once he came (the Blast quest past its first stage), Myotismon in his shape before.
TRIALS = [
    ("Oikawa", [364, 365, 236], [56, 58, 60]),        # Mummymon, Arukenimon, VenomMyotismon (his MaloMyotismon)
    ("Sepikmon", [193, 215, 237], [60, 62, 64]),      # Gryphonmon, SkullMammothmon, Kimeramon: what he hunted
    ("Gennai", [269, 178, 337], [63, 65, 67]),        # Valkyrimon, Knightmon, Zanbamon: the guardians he kept
    ("Myotismon", [231, 115, 228], [63, 65, 67]),     # Puppetmon, Machinedramon, Piedmon: the Dark Masters
]
# The Oikawa's arc (definitive_story.c, step 27): he blocks the way out of the Bug Maze Pit, around the party's level
# there (~30). The owner's Dinohyumon and MaloMyotismon are not on the disc: Mummymon and VenomMyotismon stand in, the
# same team he brings again to the Time Room.
ARC = ("Oikawa's arc", [365, 364, 236], [28, 30, 32])  # Arukenimon, Mummymon, VenomMyotismon


def table(trials=None):
    c = g.constants()
    names, _order = g.species()
    rows, battles = g.battle_rows()
    out = []
    for who, species, levels in trials or TRIALS:
        assert all(s in names for s in species), (who, species)
        st = [g.stage_of(s, lv, rows, battles, c) for s, lv in zip(species, levels)]
        top = levels[-1]
        cand = [i for i, b in enumerate(battles)
                if b["kind"] == 2 and b["escape"] and b["rows"] and i not in g.SPECIAL
                and not any(rows[r][0] in species or rows[r][0] in g.FINAL_BOSS for r in b["rows"])]
        battle = min(cand, key=lambda i: (abs(max(rows[r][1] for r in battles[i]["rows"]) - top), i))
        out.append(dict(who=who, stages=st, battle=battle, names=[names[s] for s in species]))
    return out


def c_text(rows):
    lines = ["/* Generated by tools/gen_time_room.py: the Time Room's trials (the gatekeeper before the Warp Gate), each",
             " * the challenger's three enemy members and the boss battle it is set up as. Regenerate instead of editing. */",
             '#include "definitive.h"', "", "const DefTimeTrial def_time_trials[DEF_TIME_TRIALS] = {"]
    for k, r in enumerate(rows):
        desc = ", ".join(f"{n} Lv{s['level']}" for n, s in zip(r["names"], r["stages"]))
        lines.append(f"    /* {k} {r['who']}: {desc} */")
        st = ", ".join(f"{{ {s['digimon']}, {s['level']}, {s['hp']}, {s['mp']}, {s['stat_scale']} }}" for s in r["stages"])
        lines.append(f"    {{ {{ {st} }}, {r['battle']} }},")
    lines.append("};")
    r = table([ARC])[0]
    desc = ", ".join(f"{n} Lv{s['level']}" for n, s in zip(r["names"], r["stages"]))
    st = ", ".join(f"{{ {s['digimon']}, {s['level']}, {s['hp']}, {s['mp']}, {s['stat_scale']} }}" for s in r["stages"])
    lines += ["", f"/* {r['who']}: {desc} */", f"const DefTimeTrial def_oikawa_fight = {{ {{ {st} }}, {r['battle']} }};"]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    rows = table()
    text = c_text(rows)
    if a.apply:
        GEN.write_text(text)
        print(f"wrote {GEN.relative_to(ROOT)}")
    else:
        print(text)


if __name__ == "__main__":
    main()
