#!/usr/bin/env python3
"""The map graph of the Super Rare hunts' compass: which maps an exit leads to from
each map, and which maps have random encounters (where a Super Rare can sit).

  tools/venv/bin/python tools/gen_map_graph.py           # summary only
  tools/venv/bin/python tools/gen_map_graph.py --apply   # write port/game/definitive_map_graph.c

Reads each stage file's map from its header comment and its FieldstgMapEvent table (include/fieldstg.h): an event of
type 1 (or 14, the same with a fade) is an exit, `param` the map it leads to. The flags that gate an exit (the story's)
are ignored: the compass counts the way, not whether it is open yet. Edges are directed (an exit one way only stays so).
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import gen_hunt_targets as gh  # noqa: E402

GEN = ROOT / "port/game/definitive_map_graph.c"
EXITS = (1, 14)


def graph():
    edges = defaultdict(set)
    wild = set()
    maps = set()
    for path in sorted((ROOT / "src/wstag").glob("wstag*.c")):
        s = path.read_text()
        st = re.search(r"/\* WSTAG(\d+): stage (0x[0-9A-Fa-f]+|\d+)", s)
        if not st:
            continue
        m = int(st.group(2), 0)
        maps.add(m)
        for body in re.findall(r"FieldstgMapEvent \w+\[\d+\] = \{(.*?)\n\};", s, re.S):
            for row in re.findall(r"\{([^{}]*)\}", body):
                v = gh.ints(row)
                if len(v) >= 6 and v[4] in EXITS and v[5] != m:
                    edges[m].add(v[5])
                    maps.add(v[5])
        if any(enc for enc, _ in gh.stage_lists(path)):
            wild.add(m)
    return sorted(maps), edges, wild


def write_c(maps, edges, wild):
    index = {m: i for i, m in enumerate(maps)}
    first, flat = [], []
    for m in maps:
        first.append(len(flat))
        flat += sorted(index[d] for d in edges[m] if d in index)
    first.append(len(flat))

    def rows(vals, fmt, per=12):
        return ["    " + ", ".join(fmt(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]

    lines = ["/* Generated by tools/gen_map_graph.py --apply: the maps the stages' exits lead to (the Super Rare hunts'",
             " * compass). Regenerate instead of editing. */",
             '#include "definitive.h"', "",
             f"const int def_map_node_count = {len(maps)};", "",
             f"const unsigned short def_map_nodes[{len(maps)}] = {{"] + rows(maps, lambda v: f"0x{v:03X}") + ["};", "",
             f"const unsigned short def_map_first[{len(first)}] = {{"] + rows(first, str) + ["};", "",
             f"const unsigned short def_map_edges[{max(1, len(flat))}] = {{"] + rows(flat or [0], str) + ["};", "",
             f"const unsigned char def_map_wild[{len(maps)}] = {{"] + rows([int(m in wild) for m in maps], str, 24) + ["};", ""]
    GEN.write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    maps, edges, wild = graph()
    print(f"{len(maps)} maps, {sum(len(e) for e in edges.values())} exits, {len(wild)} with random encounters")
    if args.apply:
        write_c(maps, edges, wild)
        print(f"written {GEN}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
